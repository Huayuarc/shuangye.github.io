#!/usr/bin/env python3
"""Generate the dependency-free built-in skill adapter from pinned MIT sources.

Run from the repository root. Never changes vendor/apelin. Swift strings remain
Swift source, preserving raw literals, indentation and companion file contents.
"""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'vendor/apelin/Packages/ApelinAgent/Sources/ApelinAgent/Skills'
OUTPUT = ROOT / 'src/ios/Agent/Chat/MinisApelinBuiltInSkills.swift'
SCHEMA = ROOT / 'vendor/apelin/Documents/Schemas/apelin-project.schema.json'


def generate():
    inputs = [SOURCE / 'BuiltInSkills.swift', *sorted((SOURCE / 'BuiltIn').glob('*.swift'))]
    assert len(inputs) == 15, 'Pinned v0.4.7 built-in source inventory changed'
    parts = [
        '// Generated by scripts/generate_apelin_skills.py; do not edit.\n'
        '// Apelin v0.4.7 (MIT), commit 05d899306d010dd739a4c03fcbf26825813d28c3.\n'
        '// Original license: vendor/apelin/LICENSE.\nimport Foundation\n\n'
        'struct MinisApelinSkillDocument {\n'
        '    let name: String\n    let description: String\n    let body: String\n'
        '    var files: [String: String] = [:]\n}\n'
    ]
    schema = SCHEMA.read_text()
    # A raw multiline literal avoids changing JSON backslashes in Swift.
    assert '"""###' not in schema
    parts.append('private enum MinisApelinProjectSchema {\n'
                 '    static let text = ###"""\n' + schema.rstrip() + '\n"""###\n}\n')
    for path in inputs:
        text = path.read_text()
        text = text.replace('import enum ApelinProject.ProjectValidation\n', '')
        text = text.replace('BuiltInSkills', 'MinisApelinBuiltInSkills')
        text = text.replace('SkillDocument', 'MinisApelinSkillDocument')
        text = text.replace('ProjectValidation.schemaText', 'MinisApelinProjectSchema.text')
        parts.append('// Source: ' + str(path.relative_to(ROOT)) + '\n' + text)
    return '\n'.join(parts), {
        str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in [*inputs, SCHEMA]
    }


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text, digests = generate()
    manifest = ROOT / 'docs/apelin-skill-sources.json'
    record = json.dumps({'upstreamCommit': '05d899306d010dd739a4c03fcbf26825813d28c3',
                         'sha256': digests}, indent=2, sort_keys=True) + '\n'
    if args.check:
        assert OUTPUT.read_text() == text, 'Regenerate built-in Swift skill source'
        assert manifest.read_text() == record, 'Regenerate skill source manifest'
        print('Verified 14 built-in skills, companion files and pinned schema source')
    else:
        OUTPUT.write_text(text)
        manifest.write_text(record)
        print('Generated dependency-free Apelin built-in skill source')
